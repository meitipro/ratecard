#!/usr/bin/env python3
"""
Generate the docs pages and site data that are copies of the contract.

    python scripts/gen_docs.py           # write the files
    python scripts/gen_docs.py --check   # exit 1 if any file differs from what would be written

A method cannot exist in the code and be missing from the docs, and the judge
prompt on the site cannot drift from the one validators read, because both are
written from contracts/ratecard.py by this script, and a test runs --check.

Writes:
  web/content/docs/reference/contract.mdx   every public method, from the source
  web/content/docs/reference/errors.mdx     every refusal sentence, from the source
  web/content/docs/more/judge-prompt.mdx    the judge prompt, word for word
  web/lib/contract.generated.json           limits, verdicts and the prompt, for the site
"""

from __future__ import annotations

import ast
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "ratecard.py"
DOCS = ROOT / "web" / "content" / "docs"

HEADER = "{/* Generated by scripts/gen_docs.py from contracts/ratecard.py. Do not edit by hand. */}\n\n"


def load():
    source = CONTRACT.read_text(encoding="utf-8")
    return source, ast.parse(source)


def constant(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and ast.unparse(node.targets[0]) == name:
            try:
                return ast.literal_eval(node.value)
            except ValueError:
                return ast.unparse(node.value)
    raise KeyError(name)


def constant_expr(tree: ast.Module, name: str, judge: str) -> str:
    """JUDGE_REVERSED is computed from JUDGE in the contract; rebuild it the same way for the docs."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and ast.unparse(node.targets[0]) == "JUDGE_REVERSED":
            forward = constant(tree, "LADDER_FORWARD")
            backward = constant(tree, "LADDER_REVERSED")
            return judge.replace(forward, backward)
    raise KeyError(name)


def contract_class(tree: ast.Module) -> ast.ClassDef:
    return next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Ratecard")


def kind_of(node: ast.FunctionDef) -> str:
    for deco in node.decorator_list:
        text = ast.unparse(deco)
        if text == "gl.public.write":
            return "write"
        if text == "gl.public.write.payable":
            return "payable"
        if text == "gl.public.view":
            return "view"
    return ""


def mdx_text(text: str) -> str:
    """Plain prose into MDX: braces and angle brackets would be read as code."""
    return text.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;")


def signature(node: ast.FunctionDef) -> str:
    args = ", ".join(f"{a.arg}: {ast.unparse(a.annotation)}" for a in node.args.args[1:])
    returns = ast.unparse(node.returns) if node.returns else "None"
    return f"{node.name}({args}) -> {returns}"


def methods(tree: ast.Module) -> list[dict]:
    out = []
    for node in contract_class(tree).body:
        if isinstance(node, ast.FunctionDef) and kind_of(node):
            doc = ast.get_docstring(node) or ""
            out.append(
                {
                    "name": node.name,
                    "kind": kind_of(node),
                    "signature": signature(node),
                    "args": [{"name": a.arg, "type": ast.unparse(a.annotation)} for a in node.args.args[1:]],
                    "returns": ast.unparse(node.returns) if node.returns else "None",
                    "doc": " ".join(doc.split()),
                    "line": node.lineno,
                }
            )
    return out


def refusals(tree: ast.Module) -> list[dict]:
    """Every UserError sentence, with the method it can come from. Dynamic parts read as '…'."""

    def text_of(expr: ast.AST) -> tuple[str, str]:
        parts: list[str] = []

        def walk(e: ast.AST) -> None:
            if isinstance(e, ast.BinOp) and isinstance(e.op, ast.Add):
                walk(e.left)
                walk(e.right)
            elif isinstance(e, ast.Constant) and isinstance(e.value, str):
                parts.append(e.value)
            elif isinstance(e, ast.Name) and e.id in ("E", "L"):
                parts.append("\x00" + e.id)
            else:
                parts.append("…")

        walk(expr)
        prefix = parts[0][1:] if parts and parts[0].startswith("\x00") else ""
        body = "".join(p for p in parts if not p.startswith("\x00"))
        return prefix, body

    owner: dict[int, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            for inner in ast.walk(node):
                if hasattr(inner, "lineno"):
                    owner.setdefault(inner.lineno, node.name)
    rows: dict[tuple, dict] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and ast.unparse(node.func) == "gl.vm.UserError" and node.args:
            prefix, body = text_of(node.args[0])
            key = (prefix, body)
            where = owner.get(node.lineno, "")
            row = rows.setdefault(key, {"prefix": prefix, "text": body, "where": []})
            if where and where not in row["where"]:
                row["where"].append(where)
    return sorted(rows.values(), key=lambda r: (r["prefix"], r["text"]))


def build() -> dict[pathlib.Path, str]:
    source, tree = load()
    judge = constant(tree, "JUDGE")
    judge_sha = hashlib.sha256(judge.encode("utf-8")).hexdigest()
    listed = methods(tree)
    errors = refusals(tree)
    files: dict[pathlib.Path, str] = {}

    # -- contract reference --------------------------------------------------
    kinds = {"write": "write", "payable": "write, payable", "view": "view"}
    lines = [
        "---",
        "title: Contract reference",
        "description: Every public method of contracts/ratecard.py, generated from the source.",
        "---",
        "",
        HEADER.strip(),
        "",
        f"One contract, {len(listed)} methods: {sum(1 for m in listed if m['kind'] != 'view')} writes and "
        f"{sum(1 for m in listed if m['kind'] == 'view')} views. This page is written from the contract source by "
        "`scripts/gen_docs.py`, and a test fails if the two drift, so a method cannot exist in code and be missing here.",
        "",
        "Views return JSON text. An unknown id reads as `{\"found\": false}` rather than an error, because a view that "
        "raises reaches a client only as \"execution failed\".",
        "",
        "| Method | Kind | What it does |",
        "|---|---|---|",
    ]
    for m in listed:
        first = mdx_text(m["doc"].split(". ")[0].rstrip(".")) + "."
        lines.append(f"| [`{m['name']}`](#{m['name'].replace('_', '-')}) | {kinds[m['kind']]} | {first} |")
    lines.append("")
    for m in listed:
        lines += [
            f"## {m['name']}",
            "",
            "```python",
            m["signature"],
            "```",
            "",
            f"**{kinds[m['kind']].capitalize()}.** {mdx_text(m['doc'])}",
            "",
        ]
        own = [e for e in errors if m["name"] in e["where"]]
        if own:
            lines.append("Refusals raised in the method itself (helpers such as the tier and text checks add their own, listed on the Errors page):")
            lines.append("")
            for e in own:
                lines.append(f"- `[{'EXPECTED' if e['prefix'] == 'E' else 'LLM_ERROR'}] {e['text']}`")
            lines.append("")
        lines.append(
            f"[Source, line {m['line']}](https://github.com/meitipro/ratecard/blob/main/contracts/ratecard.py#L{m['line']})"
        )
        lines.append("")
    files[DOCS / "reference" / "contract.mdx"] = "\n".join(lines)

    # -- errors --------------------------------------------------------------
    lines = [
        "---",
        "title: Errors",
        "description: Every refusal the contract can raise, generated from the source.",
        "---",
        "",
        HEADER.strip(),
        "",
        "A refused write still reaches consensus: validators agree the refusal is the right result, and the transaction "
        "reads ACCEPTED. The site counts a write as done only when the status is ACCEPTED or FINALIZED **and** the "
        "execution returned; otherwise it shows the sentence below, which the transaction carries in its result payload.",
        "",
        "`[EXPECTED]` refusals are deterministic and identical on every validator. `[LLM_ERROR]` means a model answer "
        "could not be read; validators then disagree on purpose, so the round rotates to a committee that can answer, "
        "and nothing defaults to a verdict.",
        "",
        "| Refusal | Raised in |",
        "|---|---|",
    ]
    for e in errors:
        tag = "EXPECTED" if e["prefix"] == "E" else "LLM_ERROR"
        where = ", ".join(f"`{w}`" for w in e["where"])
        lines.append(f"| `[{tag}] {e['text']}` | {where} |")
    lines.append("")
    files[DOCS / "reference" / "errors.mdx"] = "\n".join(lines)

    # -- judge prompt --------------------------------------------------------
    reverse = constant_expr(tree, "JUDGE_REVERSED", judge)
    lines = [
        "---",
        "title: The judge prompt, word for word",
        "description: The exact text every validator's model reads, copied from the contract.",
        "---",
        "",
        HEADER.strip(),
        "",
        "This is the `JUDGE` constant in `contracts/ratecard.py`, the text of section 3 of the build spec. The six "
        "values in braces are filled per sizing: the five anchors, and the claim. Every anchor and the claim are fenced "
        "before they are inserted: every `<` becomes `(` and every `>` becomes `)`, so no text can close its own block "
        "and open a forged one. Storage keeps what was written; only the prompt copy is fenced.",
        "",
        "```text",
        judge.replace("{{", "{").replace("}}", "}"),
        "```",
        "",
        f"SHA-256 of the constant: `{judge_sha}`.",
        "",
        "## The reversed reading",
        "",
        "An appeal reads the claim again with the ladder shown largest first. The prompt is the same text; only the "
        "ladder block changes, and every label stays on its own example:",
        "",
        "```text",
        reverse.split("\n\nCLAIM")[0].replace("{{", "{").replace("}}", "}").split("\n\n", 1)[1],
        "```",
        "",
        "## How validators agree",
        "",
        "The leader asks its model and returns one string, the label: XS, S, M, L, XL or NONE. Each validator asks its "
        "own model the same prompt and agrees only when its own label is exactly the leader's. Nothing else is compared "
        "and nothing else is stored from the model, so agreeing on the label is agreeing on the pay.",
        "",
        "The price is then looked up on the card by the label, and the cap is applied, in contract code. The model never "
        "sees a price. Between two tiers the prompt picks the smaller, a deliberate tie break so a pool is never overspent "
        "by a generous reading; the appeal exists for the cases where that is unfair.",
        "",
        "An answer that cannot be read (not JSON, or a label outside the six) is retried once, then fails the round. It "
        "never becomes a label.",
        "",
    ]
    files[DOCS / "more" / "judge-prompt.mdx"] = "\n".join(lines)

    # -- site data -----------------------------------------------------------
    data = {
        "source": "contracts/ratecard.py",
        "judge": judge.replace("{{", "{").replace("}}", "}"),
        "judgeSha256": judge_sha,
        "tiers": list(constant(tree, "TIERS")),
        "labels": list(constant(tree, "LABELS")),
        "limits": {
            "name": constant(tree, "MAX_NAME"),
            "anchors": constant(tree, "ANCHORS"),
            "anchor": constant(tree, "MAX_ANCHOR"),
            "work": constant(tree, "MAX_WORK"),
            "minWindowHours": constant(tree, "MIN_WINDOW_H"),
            "maxWindowHours": constant(tree, "MAX_WINDOW_H"),
            "page": constant(tree, "MAX_PAGE"),
        },
        "methods": [{k: m[k] for k in ("name", "kind", "signature", "doc")} for m in listed],
    }
    files[ROOT / "web" / "lib" / "contract.generated.json"] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"

    files[DOCS / "more" / "evaluation.mdx"] = evaluation_page()
    files[DOCS / "reference" / "addresses.mdx"] = addresses_page()
    files.update(synced_includes())
    return files


# -- evaluation, from eval/results.json -----------------------------------------------
def evaluation_page() -> str:
    results = json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))
    golden = json.loads((ROOT / "eval" / "golden.json").read_text(encoding="utf-8"))
    explorer = results["explorer"]
    by_case: dict[str, list[dict]] = {}
    for r in results["runs"]:
        if r.get("label"):
            by_case.setdefault(r["case"], []).append(r)
    for rows in by_case.values():
        rows.sort(key=lambda r: r["run"])
    scored = [c for c in golden["cases"] if not c.get("held_out")]
    first_hits = sum(1 for c in scored if by_case.get(c["id"]) and by_case[c["id"]][0]["label"] == c["expected"])
    all_n = sum(len(by_case.get(c["id"], [])) for c in scored)
    all_hits = sum(1 for c in scored for r in by_case.get(c["id"], []) if r["label"] == c["expected"])
    stable = sum(1 for c in scored if len(by_case.get(c["id"], [])) >= 3 and len({r["label"] for r in by_case[c["id"]]}) == 1)
    unstable = sum(1 for c in scored if len(by_case.get(c["id"], [])) >= 3 and len({r["label"] for r in by_case[c["id"]]}) > 1)
    lines = [
        "---",
        "title: Evaluation results with transactions",
        "description: Thirteen golden and held-out claims through real consensus on the deployed contract, each golden claim read three times, reported as they came out.",
        "---",
        "",
        "{/* Generated by scripts/gen_docs.py from eval/results.json. Do not edit by hand. */}",
        "",
        f"Every reading below is one `claim` and one `size` on the deployed contract, "
        f"[`{results['contract']}`]({explorer}/address/{results['contract']}), and every label was read back from the "
        "contract with `get_claim`. The card is a copy of the Kiln ladder with the prices divided by 100 and a review "
        "window of 0, so the pool lasts and each claim can be sized at once. The model never sees a price, so the "
        "labels do not depend on them.",
        "",
        f"- **Golden claims, first reading: {first_hits} of {len(scored)}** matched the expected label.",
        f"- **All readings: {all_hits} of {all_n}** matched.",
        f"- **Stability:** each golden claim was read three times. {stable} came back identical every time and {unstable} did not.",
        "- **Held-out claims:** reported with no expected label, exactly as they came out, and read once.",
        f"- `eval/golden.json` was hashed and timestamped before the first run: sha256 `{results['golden_sha256']}`, "
        f"locked at {results['golden_locked_at']}.",
        f"- The judge prompt is the spec's, word for word (sha256 `{results['judge_sha256']}`). Nothing was tuned.",
        "",
        "| Case | Claim | Expected | Run 1 | Run 2 | Run 3 | Stable |",
        "|---|---|---|---|---|---|---|",
    ]
    for case in golden["cases"]:
        rows = {r["run"]: r for r in by_case.get(case["id"], [])}
        cells = []
        for number in (1, 2, 3):
            r = rows.get(number)
            if not r:
                cells.append("")
                continue
            mark = "" if case["expected"] == "EITHER" else (" ✓" if r["label"] == case["expected"] else " ✗")
            cells.append(f"[{r['label']}{mark}]({explorer}/tx/{r['size_tx']})")
        have = [r["label"] for r in rows.values()]
        if case.get("held_out"):
            steady = "once"
        elif len(have) >= 3:
            steady = "yes" if len(set(have)) == 1 else "**no**"
        else:
            steady = "pending"
        lines.append(f"| {case['id']}{' (held out)' if case.get('held_out') else ''} | {mdx_text(case['claim'])} | {case['expected']} | {cells[0]} | {cells[1]} | {cells[2]} | {steady} |")
    tries = [(r, t) for r in results["runs"] for t in r["tries"] if t.get("consensus") != "decided"]
    lines += ["", "## Every try", ""]
    if tries:
        lines.append("Tries whose size produced no label, each followed by another size of the same claim:")
        lines.append("")
        for r, t in tries:
            lines.append(f"- case {r['case']} run {r['run']}: {mdx_text(str(t['consensus']))} ([tx]({explorer}/tx/{t['tx']}))")
    else:
        lines.append("Every claim produced a label on its first size; nothing was sent twice.")
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "python eval/run_golden.py            # run 1 of every golden claim not yet read",
        "python eval/run_golden.py H1 H2 H3   # the held-out claims, once",
        "python eval/stability.py             # runs 2 and 3, and every disagreement",
        "```",
        "",
        "The scripts refuse to run if `eval/golden.json` no longer matches its locked hash, never send a read claim "
        "again, and save each try before printing it. Every try is in `eval/results.json`.",
        "",
    ]
    return "\n".join(lines)


